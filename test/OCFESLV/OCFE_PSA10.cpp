// OCFE_PSA10b.cpp  ---  THE ACTUAL PSA REGIME: self-sharpening fronts, and the oscillations
//                      they generate.  DEMONSTRATION driver for the limiter/WENO case.
// ===========================================================================
// WHY THIS DRIVER EXISTS -- correcting the arc's framing
// ------------------------------------------------------
// PSA6..PSA9b measured the rung-9 model AS SHIPPED: D_ax = 0.1, k_ldf = 2.0, U = L = 1.
// Those numbers put the bed nowhere near a real PSA:
//
//     Pe = U*L/D_ax = 10          dispersive front width  ~ D/u_shock = 0.15  = 15% OF THE BED
//     LDF mass-transfer zone      ~ U*F*(dq*/dc)/k_ldf    = 0.25  = 25% OF THE BED
//     u_shock = U/(1+F*dq*/dc)    = 0.667                 (Langmuir, c 0 -> 0.5)
//
// i.e. the front is smeared over a quarter of the column and covered by ~4.5 collocation
// nodes.  The model CANNOT support a sharp front, so the arc found none, and the only
// oscillation left to find was the t=0 corner artefact -- real, but incidental.  Real PSA
// beds run Pe ~ 1e2..1e3 with fast kinetics, where the FAVOURABLE Langmuir isotherm makes the
// concentration front SELF-SHARPEN into a shock as it travels.  That is the regime in which
// flux limiters / WENO-type reconstruction are the standard remedy, and it has never been
// exercised here.
//
// THE SHARPNESS KNOB
// ------------------
// One parameter S drives the bed toward the low-dispersion, local-equilibrium limit:
//        D_ax = D0/S      lam = lam0/S      k_ldf = k0*S
// so dispersive and kinetic front widths shrink together and stay comparable (they would
// otherwise trade off and the front would stall at whichever is larger).  S = 1 is the model
// the whole arc used.  S = 100 gives Pe = 1000 and both widths ~0.2% of the bed -- about
// 1/15 of one collocation interval on the shipped z-mesh.
//
// WHAT IS DELIBERATELY REMOVED, so the measurement is unambiguous
// ---------------------------------------------------------------
// 1. THE STARTUP CORNER.  PSA5..PSA9's feed sits at cA against an empty bed, giving a
//    discontinuity at (z=0,t=0) -- which PSA9 showed is the dominant undershoot in that
//    configuration.  Here the feed is multiplied by a SHIFTED-NORMALISED tanh ramp,
//    r(0) = 0 and r(inf) = 1 EXACTLY, of width eps0 = 0.05 which the t-mesh resolves.  The
//    corner artefact is gone by construction.  (At high S it would NOT dissipate -- low D
//    means nothing smooths it -- so leaving it in would contaminate the whole field.)
// 2. THE INLET SWITCH IN t.  The composition switch at t*=2 has width eps and the t-mesh
//    always brackets it with 2 elements of width 4*eps (PSA7's law, W = 4*eps).  So the
//    inlet DATUM is resolved in t.
// => Whatever oscillation remains is generated by the SPATIAL FRONT INSIDE THE BED, which is
//    what a limiter would act on.  This is the point of the driver.
//
// AXES
// ----
//   A  S in {1,3,10,30,100} at the shipped z-mesh (5x6), sharp switch (eps=1e-3).
//      Onset and growth of the oscillation as the bed approaches the PSA limit.
//   B  z-refinement at high S (ne_z 5/10/20/40) -- what brute force actually costs.
//   C  SMOOTH inlet (eps=0.5) at high S.  THE DECISIVE CONFIG: if a sharp front forms and
//      rings anyway, the problem is NOT the inlet datum, it is the isotherm self-sharpening
//      the front internally -- and no amount of inlet smoothing or a-priori mesh grading can
//      pre-empt it, because the front's POSITION is part of the solution.
//
// METRICS -- chosen to map onto limiter theory, not invented here
// ---------------------------------------------------------------
//   TV(c1(.,t)) = \int_0^1 |dc1/dz| dz.  The exact solution is MONOTONE in z, so its total
//   variation is exactly |c1(0,t) - c1(1,t)|.  Any oscillation strictly increases TV.
//        TV_excess = ( TV - |c1(0)-c1(1)| ) / |c1(0)-c1(1)|
//   This is the quantity a TVD scheme bounds and a limiter enforces; TV_excess ~ 0 means
//   monotone, TV_excess = 0.5 means the profile wiggles by half its own range.  Reported
//   alongside the oscillation COUNT (sign changes of dc1/dz) and the undershoot.
//   Front POSITION and WIDTH are tracked at every snapshot: the front MOVES at u_shock, so a
//   mesh graded for it at one time is wrong at every other time -- the quantitative form of
//   "you cannot grade for a front whose location is part of the solution".
//
// Emits 2-D (z,t) field maps and z-profile snapshots for the flagged configs, so the
// oscillation can be seen rather than inferred.
// ===========================================================================

